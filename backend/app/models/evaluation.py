    IDLE = "IDLE"
    DISPATCHING = "DISPATCHING"
    WAITING_CALLBACK = "WAITING_CALLBACK"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    TIMED_OUT = "TIMED_OUT"
    CANCELLED = "CANCELLED"


