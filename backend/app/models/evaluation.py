class ThreatStatus(str, enum.Enum):
    NORMAL = "NORMAL"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


@dataclasses.dataclass(frozen=True)
class SubjectProfile:
    person_detected: bool
    clothing: str
    observed_action: str
    visible_objects: tuple[str, ...]
    distinguishing_features: tuple[str, ...]


@dataclasses.dataclass(frozen=True)
class ThreatAssessment:
    threat_score: int
    status: ThreatStatus
    reasoning: str
    subject_profile: SubjectProfile

    def validate(self) -> None:
        if type(self.threat_score) is not int or not 0 <= self.threat_score <= 100:
            raise ValueError("threat_score must be an integer from 0 to 100")
        expected = (ThreatStatus.NORMAL if self.threat_score <= 34 else
                    ThreatStatus.WARNING if self.threat_score <= 64 else ThreatStatus.CRITICAL)
        if self.status is not expected:
            raise ValueError("status is inconsistent with threat_score")
        if not isinstance(self.reasoning, str) or not self.reasoning.strip():
            raise ValueError("reasoning must be nonempty")
        profile = self.subject_profile
        if not isinstance(profile, SubjectProfile) or type(profile.person_detected) is not bool:
            raise ValueError("subject_profile.person_detected must be bool")
        if not isinstance(profile.clothing, str) or not isinstance(profile.observed_action, str):
            raise ValueError("subject_profile descriptions must be strings")
        for name in ("visible_objects", "distinguishing_features"):
            value = getattr(profile, name)
            if not isinstance(value, tuple) or any(not isinstance(item, str) for item in value):
                raise ValueError(f"subject_profile.{name} must be tuple[str, ...]")


@dataclasses.dataclass(frozen=True)
class EvaluationCallback:
    """Validated, image-free result correlated to an original event/session."""

    event_id: str
    source_session_id: str
    assessment: ThreatAssessment


class CallbackDisposition(str, enum.Enum):
    ACCEPTED = "ACCEPTED"
    DUPLICATE = "DUPLICATE"
    REJECTED = "REJECTED"


class CallbackSubjectProfile(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    personDetected: StrictBool
    clothing: StrictStr = Field(max_length=512)
    observedAction: StrictStr = Field(max_length=1024)
    visibleObjects: tuple[StrictStr, ...] = Field(max_length=16)
    distinguishingFeatures: tuple[StrictStr, ...] = Field(max_length=16)


class EvaluationCallbackPayload(BaseModel):
    """Strict camelCase wire contract; the flow must emit an integer score.

    IDs are copied from Webhook metadata, not generated by Gemini. The legacy
    synchronous client's more permissive parser is retired in a later task.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    event_id: StrictStr = Field(min_length=1, max_length=128)
    source_session_id: StrictStr = Field(min_length=1, max_length=128)
    threatScore: StrictInt = Field(ge=0, le=100)
    status: ThreatStatus
    reasoning: StrictStr = Field(min_length=1, max_length=4000)
    suspectProfile: CallbackSubjectProfile

    @field_validator("event_id", "source_session_id")
    @classmethod
    def valid_identifier(cls, value: str) -> str:
        if not value.strip() or value != value.strip():
            raise ValueError("identifier must be nonempty and trimmed")
        return value

    def to_callback(self) -> EvaluationCallback:
        profile = self.suspectProfile
        assessment = ThreatAssessment(
            threat_score=self.threatScore,
            status=self.status,
            reasoning=self.reasoning,
            subject_profile=SubjectProfile(
                person_detected=profile.personDetected,
                clothing=profile.clothing,
                observed_action=profile.observedAction,
                visible_objects=profile.visibleObjects,
                distinguishing_features=profile.distinguishingFeatures,
            ),
        )
        assessment.validate()
        return EvaluationCallback(self.event_id, self.source_session_id, assessment)


